const digits = (code: string | null): string =>
  (code ?? "").replace(/\D/g, "");

/** 자세한 업종명. 4자리 → 3자리 → 2자리 순으로 찾습니다. */
export function sectorName(code: string | null): string {
  const d = digits(code);
  if (d.length >= 4 && DETAIL[d.slice(0, 4)]) return DETAIL[d.slice(0, 4)];
  if (d.length >= 3 && SUB[d.slice(0, 3)]) return SUB[d.slice(0, 3)];
  if (d.length >= 2 && MAJOR[d.slice(0, 2)]) return MAJOR[d.slice(0, 2)];
  return UNKNOWN;
}

/** 큰 묶음 이름. 자세한 업종에 회사가 적을 때 여기로 물러섭니다. */
export function sectorGroup(code: string | null): string {
  const d = digits(code);
  if (d.length >= 2 && MAJOR[d.slice(0, 2)]) return MAJOR[d.slice(0, 2)];
  return UNKNOWN;
}
