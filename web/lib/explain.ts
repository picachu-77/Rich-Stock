/**
 * 숫자를 눌렀을 때 나오는 설명.
 *
 * ★ 사전이 아니라 '이 종목의 이 숫자' 설명입니다 ★
 *   "PER 은 주가수익비율입니다" 는 도움이 안 됩니다. 모르는 말을 모르는
 *   말로 바꿔놓은 것뿐입니다. 그래서 세 덩어리로 나눕니다.
 *
 *     뜻   — 무엇을 잰 값인지, 비유로
 *     지금 — 이 종목의 실제 값이 무슨 뜻인지
 *     주의 — 이 숫자만 보고 판단하면 안 되는 이유
 *
 *   '주의' 를 반드시 답니다. 초보자가 가장 크게 다치는 지점이
 *   "PER 이 낮으니 싸다" 처럼 지표 하나를 결론으로 쓰는 것입니다.
 *   낮은 데는 대개 이유가 있고, 그 이유가 나쁜 경우가 많습니다.
 *
 * ★ 좋다·나쁘다를 말하지 않습니다 ★
 *   '높다/낮다' 같은 사실과 '무엇을 더 확인해야 하는지' 까지만 적습니다.
 *   사라·팔라는 말은 하지 않습니다. 연습하려고 보는 화면입니다.
 */
import { eok, num } from "./format";

export type Explain = {
  뜻: string;
  지금: string;
  주의: string;
};

/** 값이 없을 때 공통으로 쓰는 안내. */
const 없음 = (why: string): string =>
  `이 종목은 이 값이 비어 있습니다. ${why} 빈칸은 '0' 이 아니라 '아직 자료가 없다' 는 뜻입니다.`;

const ETF안내 =
  "ETF 는 회사가 아니라 여러 종목을 담아둔 바구니라서 재무제표가 없습니다.";

/* ── 시가총액 ─────────────────────────────────────────────── */

export function 시가총액(v: number | null): Explain {
  const 뜻 =
    "이 회사를 통째로 사려면 얼마가 드는지입니다. 주가 × 주식 수로 계산합니다. " +
    "회사의 크기는 주가가 아니라 이 값으로 봅니다.";
  const 주의 =
    "1주 가격이 싸다고 작은 회사가 아닙니다. 회사를 몇 조각으로 잘랐느냐에 따라 " +
    "1주 값이 달라질 뿐입니다. 500원짜리 주식이 5만원짜리보다 큰 회사인 경우도 흔합니다.";

  if (v === null) return { 뜻, 지금: 없음(""), 주의 };

  // 규모를 말로 바꿔줍니다. 숫자만으로는 큰지 작은지 감이 안 옵니다.
  const 규모 =
    v >= 100_000
      ? "국내에서 손꼽히는 큰 회사입니다."
      : v >= 10_000
        ? "큰 편에 드는 회사입니다."
        : v >= 1_000
          ? "중간 크기 회사입니다."
          : "작은 회사입니다. 작은 회사는 주가가 크게 흔들리는 일이 잦습니다.";

  return {
    뜻,
    지금: `**${eok(v)}** 입니다. 이 회사 전체를 사는 데 그만큼 든다는 뜻입니다. ${규모}`,
    주의,
  };
}

/* ── PER ──────────────────────────────────────────────────── */

export function PER(v: number | null, kind: string): Explain {
  const 뜻 =
    "지금 값에 회사를 샀을 때, 회사가 버는 돈으로 원금을 뽑는 데 몇 년 걸리는지입니다. " +
    "주가를 1주당 순이익으로 나눈 값입니다.";
  const 주의 =
    "**낮다고 무조건 싼 게 아닙니다.** 앞으로 못 벌 것 같으면 시장이 미리 주가를 " +
    "낮춥니다. 그래서 사양산업이나 실적이 꺾이는 회사가 PER 이 낮은 경우가 많습니다. " +
    "왜 낮은지를 먼저 봐야 합니다. 업종마다 보통 수준이 달라서 다른 업종끼리 " +
    "견주는 것도 뜻이 없습니다.";

  if (v === null || v <= 0) {
    return {
      뜻,
      지금:
        kind === "ETF"
          ? 없음(ETF안내)
          : "비어 있습니다. **회사가 적자여서 계산이 안 되는 경우가 대부분입니다.** " +
            "버는 돈이 없으면 '몇 년이면 원금을 뽑는다' 를 셀 수 없습니다. " +
            "적자 회사가 PER 0 으로 1등에 오르는 것을 막으려고 일부러 비워 둡니다.",
      주의,
    };
  }

  const 수준 =
    v < 10
      ? "국내 증시에서는 낮은 축입니다."
      : v < 20
        ? "국내 증시에서 흔히 보이는 수준입니다."
        : v < 40
          ? "높은 편입니다. 앞으로 더 벌 것이라는 기대가 값에 들어가 있습니다."
          : "아주 높습니다. 기대가 크게 반영돼 있어, 기대가 어긋나면 주가가 많이 내릴 수 있습니다.";

  return {
    뜻,
    지금: `**${num(v, 2)}** 입니다. 지금 값에 사서 회사가 지금처럼 벌면 약 **${num(Math.round(v))}년** 만에 원금을 뽑는 셈입니다. ${수준}`,
    주의,
  };
}

/* ── PBR ──────────────────────────────────────────────────── */

export function PBR(v: number | null, kind: string): Explain {
  const 뜻 =
    "회사가 가진 순재산(자산에서 빚을 뺀 것)에 견줘 주가가 몇 배인지입니다. " +
    "1 이면 '회사를 지금 정리해서 나눈 값' 과 주가가 같다는 뜻입니다.";
  const 주의 =
    "1 보다 낮다고 공짜로 줍는 게 아닙니다. 장부에 적힌 재산 값이 실제로 그만큼 " +
    "받고 팔릴지는 다른 이야기입니다. 오래된 공장이나 안 팔리는 재고가 장부에는 " +
    "비싸게 남아 있을 수 있습니다.";

  if (v === null || v <= 0) {
    return { 뜻, 지금: 없음(kind === "ETF" ? ETF안내 : ""), 주의 };
  }

  const 수준 =
    v < 1
      ? "가진 재산보다 싸게 거래되고 있습니다. 국내 증시에는 이런 회사가 꽤 많습니다."
      : v < 2
        ? "가진 재산보다 조금 비싸게 거래되고 있습니다."
        : "가진 재산보다 많이 비싸게 거래되고 있습니다. 재산보다 '앞으로 벌 힘' 을 보고 사는 값입니다.";

  return {
    뜻,
    지금: `**${num(v, 2)}배** 입니다. ${수준}`,
    주의,
  };
}

/* ── 배당수익률 ───────────────────────────────────────────── */

export function 배당수익률(v: number | null): Explain {
  const 뜻 =
    "1년에 받는 배당금이 지금 주가의 몇 %인지입니다. 은행 이자와 비슷하게 " +
    "'주식을 들고만 있어도 들어오는 돈' 입니다.";
  const 주의 =
    "**주가가 떨어져도 이 값은 올라갑니다.** 배당을 늘려서 높아진 것인지, " +
    "주가가 빠져서 높아진 것인지 꼭 나눠 봐야 합니다. 뒤쪽이면 좋은 신호가 아닙니다. " +
    "그리고 배당은 회사가 매년 새로 정합니다. 작년에 줬다고 올해도 준다는 보장은 없습니다.";

  if (v === null || v <= 0) {
    return {
      뜻,
      지금:
        "비어 있거나 0 입니다. 배당을 안 주는 회사입니다. 나쁜 것만은 아닙니다 — " +
        "번 돈을 나눠주는 대신 사업을 키우는 데 다시 쓰는 회사도 많습니다.",
      주의,
    };
  }

  const 수준 =
    v >= 5
      ? "은행 예금보다 높은 편입니다. 다만 왜 이렇게 높은지 꼭 확인하세요."
      : v >= 3
        ? "국내 증시에서 높은 축입니다."
        : v >= 1
          ? "보통 수준입니다."
          : "낮은 편입니다.";

  return {
    뜻,
    지금: `**${num(v, 2)}%** 입니다. 100만원어치를 사면 1년에 약 **${num(Math.round(v * 10_000))}원** 을 배당으로 받는 셈입니다. ${수준}`,
    주의,
  };
}

/* ── ROE ──────────────────────────────────────────────────── */

export function ROE(v: number | null, kind: string): Explain {
  const 뜻 =
    "회사가 자기 돈으로 얼마나 잘 벌었는지입니다. 100원을 굴려 1년에 몇 원을 " +
    "남겼는지를 %로 나타낸 값입니다.";
  const 주의 =
    "빚을 많이 쓰면 이 값이 저절로 올라갑니다. 자기 돈이 적을수록 나누는 수가 " +
    "작아지기 때문입니다. **그래서 ROE 는 부채비율과 반드시 같이 봐야 합니다.** " +
    "한 해만 좋았을 수도 있으니 여러 해를 보는 편이 낫습니다.";

  if (v === null) {
    return { 뜻, 지금: 없음(kind === "ETF" ? ETF안내 : ""), 주의 };
  }

  if (v < 0) {
    return {
      뜻,
      지금: `**${num(v, 2)}%** 로 마이너스입니다. **적자를 냈다는 뜻입니다.** 자기 돈을 굴려서 오히려 잃었습니다.`,
      주의,
    };
  }

  const 수준 =
    v >= 15
      ? "높은 축입니다. 돈을 잘 굴리는 회사로 봅니다."
      : v >= 8
        ? "보통 수준입니다."
        : "낮은 편입니다. 은행 예금과 견줘볼 만한 수준입니다.";

  return {
    뜻,
    지금: `**${num(v, 2)}%** 입니다. 자기 돈 100원으로 1년에 약 **${num(v, 0)}원** 을 남겼다는 뜻입니다. ${수준}`,
    주의,
  };
}

/* ── 부채비율 ─────────────────────────────────────────────── */

export function 부채비율(v: number | null, kind: string): Explain {
  const 뜻 =
    "빚이 자기 돈의 몇 %인지입니다. 100% 면 빚과 자기 돈이 같고, " +
    "200% 면 빚이 자기 돈의 두 배입니다.";
  const 주의 =
    "빚이 많다고 무조건 나쁜 회사는 아닙니다. 은행·카드·건설처럼 원래 빚을 크게 " +
    "쓰는 업종이 있습니다. **같은 업종끼리 견줘야 뜻이 있습니다.** " +
    "다만 이자를 감당할 만큼 벌고 있는지는 따로 봐야 합니다.";

  if (v === null) {
    return { 뜻, 지금: 없음(kind === "ETF" ? ETF안내 : ""), 주의 };
  }

  const 배수 = v / 100;
  const 수준 =
    v >= 400
      ? "아주 높습니다. 장사가 조금만 어려워져도 이자 갚기가 빠듯해질 수 있습니다."
      : v >= 200
        ? "높은 편입니다. 왜 이렇게 빌렸는지, 이자를 감당할 만큼 버는지 확인해 보세요."
        : v >= 100
          ? "보통 수준입니다."
          : "낮습니다. 빚이 적어 튼튼한 편입니다.";

  return {
    뜻,
    지금: `**${num(v, 0)}%** 입니다. 빚이 자기 돈의 **${num(배수, 1)}배** 라는 뜻입니다. ${수준}`,
    주의,
  };
}

