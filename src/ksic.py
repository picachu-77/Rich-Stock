UNKNOWN = "업종 미상"


def sector_name(induty_code: str | None) -> str:
    """
    DART 업종코드를 한글 업종명으로 바꿉니다.

    코드가 없거나 표에 없는 값이면 '업종 미상'을 돌려줍니다.
    (업종 미상인 종목은 화면에서 '같은 업종 비교' 대상에서 빠집니다)
    """
    if not induty_code:
        return UNKNOWN
    digits = "".join(ch for ch in str(induty_code) if ch.isdigit())
    if len(digits) < 2:
        return UNKNOWN
    return KSIC_MAJOR.get(digits[:2], UNKNOWN)
