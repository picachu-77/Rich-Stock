def _digits(induty_code: str | None) -> str:
    return "".join(ch for ch in str(induty_code or "") if ch.isdigit())


def sector_name(induty_code: str | None) -> str:
    """
    업종코드를 '자세한 업종명'으로 바꿉니다.

    4자리 → 3자리 → 2자리 순서로 찾아보고, 아무것도 없으면 '업종 미상'.
    예) 26410 → 통신·방송장비 (3자리 264 로 찾음)
    """
    d = _digits(induty_code)
    if len(d) >= 4 and d[:4] in KSIC_DETAIL:
        return KSIC_DETAIL[d[:4]]
    if len(d) >= 3 and d[:3] in KSIC_SUB:
        return KSIC_SUB[d[:3]]
    if len(d) >= 2 and d[:2] in KSIC_MAJOR:
        return KSIC_MAJOR[d[:2]]
    return UNKNOWN


def sector_group(induty_code: str | None) -> str:
    """
    업종코드를 '큰 묶음' 이름으로 바꿉니다.

    자세한 업종에 회사가 너무 적어 순위 비교가 어려울 때,
    이 큰 묶음으로 다시 비교하기 위해 씁니다.
    예) 26410 → 전자·통신장비
    """
    d = _digits(induty_code)
    if len(d) >= 2 and d[:2] in KSIC_MAJOR:
        return KSIC_MAJOR[d[:2]]
    return UNKNOWN
